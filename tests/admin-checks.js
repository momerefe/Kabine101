// Yönetici akışlarını gerçek form ve düğmelerle denetler. Test tarayıcısı geçicidir.
(async () => {
  const checks = [];
  const check = (name, condition) => checks.push({ name, passed: Boolean(condition) });
  const wait = (ms = 80) => new Promise(resolve => setTimeout(resolve, ms));
  const navigate = async hash => { location.hash = hash; await wait(); };
  const click = selector => { const element = document.querySelector(selector); if (!element) throw new Error(`Kontrol bulunamadı: ${selector}`); element.click(); };
  const input = (selector, value) => { const element = document.querySelector(selector); element.value = value; element.dispatchEvent(new Event('input', { bubbles: true })); element.dispatchEvent(new Event('change', { bubbles: true })); };
  const submit = async (selector, button = '') => { const form = document.querySelector(selector); form.requestSubmit(button ? form.querySelector(button) : undefined); await wait(); };
  const confirm = async () => { await submit('#confirmation-form'); };
  const s = KOC_STORE;
  const tomorrowYear = Number(s.today().slice(0, 4)) + 1;

  await navigate('admin/overview');
  check('Öğrenci oturumu yönetim ekranını açamaz (demo)', document.querySelector('main h2').textContent.includes('yönetici demosuna'));
  click('[data-action=logout]');
  click('[data-auth-audience=admin]');
  input('#admin-email', 'deniz@ogrenci.example'); await submit('#admin-auth-form');
  check('Öğrenci hesabı ayrı yönetici formunda reddedilir', !document.querySelector('#admin-auth-error').hidden);
  input('#admin-email', 'yonetici@ogrenci.example'); await submit('#admin-auth-form');
  check('Yönetici hesabı yönetim paneline yönlenir', location.hash === '#admin/overview' && document.body.classList.contains('is-admin'));
  check('12 yönetici navigasyon bağlantısı', document.querySelectorAll('#desktop-nav a').length === 12);
  const sections = ['overview', 'partners', 'businesses', 'benefits', 'students', 'published', 'archived', 'usage', 'analytics', 'users', 'audit', 'settings'];
  for (const section of sections) {
    await navigate(`admin/${section}`);
    check(`Yönetici bölümüne erişim: ${section}`, document.querySelector('main h1') && document.querySelector(`#desktop-nav a[href="#admin/${section}"]`).getAttribute('aria-current') === 'page');
  }
  await navigate('admin/usage');
  check('Kullanım ekranında sahte kayıt üretilmez', !document.querySelector('main tbody') && document.querySelector('.admin-empty').textContent.includes('Doğrulanmış kullanım kaydı bulunmuyor'));
  await navigate('admin/businesses?new=1');
  input('#edit-name', 'Test İşletmesi (Demo)'); input('#edit-description', 'Yalnızca test için kurgusal işletme.');
  input('#edit-contactPerson', 'Örnek temsilci'); input('#edit-contact', 'temsilci@example.org'); input('#edit-branches', 'Demo merkez şube');
  input('#edit-partnershipStatus', 'active'); input('#edit-notes', 'Örnek görüşme notu.');
  await submit('#business-form');
  const business = s.businesses.find(item => item.name === 'Test İşletmesi (Demo)');
  check('İşletme ekleme ve listeye dönüş', Boolean(business) && location.hash === '#admin/businesses');
  await navigate(`admin/businesses?view=${business.id}`);
  check('İşletme detayı ve iletişim alanları', document.querySelector('.admin-business-detail').textContent.includes('temsilci@example.org'));
  await navigate(`admin/businesses?edit=${business.id}`);
  input('#edit-notes', 'Güncellenmiş demo notu.'); await submit('#business-form');
  check('İşletme düzenleme', business.notes === 'Güncellenmiş demo notu.');
  await navigate('admin/partners'); input('#admin-search', 'Güncellenmiş');
  check('İş ortaklığı araması', document.querySelectorAll('.admin-table tbody tr').length === 1);
  input('#admin-filter', 'ended');
  check('İş ortaklığı filtre ve boş sonuç', document.querySelector('.admin-empty'));

  await navigate('admin/benefits?new=1');
  input('#edit-businessId', business.id); input('#edit-title', 'Test avantajı %25'); input('#edit-discount', '%25');
  await submit('#benefit-form', '[value=draft]');
  const benefit = s.benefits.find(item => item.title === 'Test avantajı %25');
  check('Avantajı taslak kaydetme', benefit?.publicationStatus === 'draft');
  await navigate(`benefit/${benefit.id}`);
  check('Yönetici taslak önizlemesi kullanım açmaz', document.querySelector('[data-benefit-state=draft]') && !document.querySelector('[data-action=reveal]') && !document.querySelector('[data-favorite]'));
  await navigate(`admin/benefits?edit=${benefit.id}`);
  input('#edit-description', 'Örnek ürünlerde test avantajı.'); input('#edit-conditions', 'Yalnızca örnek ürünler.\nDiğer kampanyalarla birleşmez.');
  input('#edit-instructions', 'Demo kodunu göster.\nKopyala.'); input('#edit-code', 'DEMO-TEST25');
  input('#edit-validUntil', `${tomorrowYear}-12-31`); input('#edit-products', 'Örnek kahve'); input('#edit-exceptions', 'Paketli ürünler hariç.'); input('#edit-minimumSpend', '100');
  await submit('#benefit-form', '[value=publish]');
  check('Koşul kontrolü olmadan yayın reddedilir', !document.querySelector('.form-error').hidden && !document.querySelector('#admin-dialog').open);
  document.querySelector('[name=reviewed]').checked = true;
  await submit('#benefit-form', '[value=publish]');
  check('Yayınlama için onay penceresi', document.querySelector('#admin-dialog').open);
  click('#admin-dialog [data-admin=close-dialog]');
  check('Yayın onayını iptal etme', benefit.publicationStatus === 'draft');
  await submit('#benefit-form', '[value=publish]'); await confirm();
  check('Demo yayın ve tarih bilgisi', benefit.publicationStatus === 'published' && benefit.publishedAt === s.today());
  await navigate('admin/published'); input('#admin-search', 'Test avantajı');
  check('Yayımlanmış avantaj araması', document.querySelectorAll('.admin-table tbody tr').length === 1);
  click(`[data-admin=suspend][data-id="${benefit.id}"]`); await confirm();
  check('Onayla askıya alma', s.statusOf(benefit) === 'suspended');
  await navigate('admin/archived');
  check('Askı nedeninin listede açıklanması', document.querySelector('main').textContent.includes('Yönetici tarafından askıya alındı.'));
  await navigate(`admin/benefits?edit=${benefit.id}`);
  input('#edit-validUntil', '2020-01-01'); document.querySelector('[name=reviewed]').checked = true;
  await submit('#benefit-form', '[value=publish]');
  check('Süresi dolmuş avantaj yeniden yayımlanamaz', document.querySelector('.form-error').textContent.includes('süresi dolmuş'));
  input('#edit-validUntil', `${tomorrowYear}-12-31`); input('#edit-method', 'membership');
  check('Kullanım yöntemi formu ilgili alanı gösterir', !document.querySelector('[data-method-fields=membership]').hidden && document.querySelector('[data-method-fields=code]').hidden);
  input('#edit-membershipLabel', 'Örnek KoçBenefits kartı');
  await submit('#benefit-form', '[value=publish]'); await confirm();
  check('Koşullar kontrol edilerek yeniden yayın', s.statusOf(benefit) === 'active' && benefit.method === 'membership' && benefit.code === '');
  await navigate(`benefit/${benefit.id}`); click('[data-action=reveal]');
  check('Üyelik kartında ilgisiz kod veya QR gösterilmez', document.querySelector('.demo-member-pass') && !document.querySelector('.qr-box') && !document.querySelector('#discount-code'));
  click('[data-action=share-benefit]'); await wait(120);
  const copied = await navigator.clipboard.readText();
  check('Paylaşılabilir benzersiz bağlantı panoya kopyalanır', copied === `${location.href.split('#')[0]}#benefit/${benefit.id}`);
  check('Tam koşullar, istisnalar ve minimum harcama görünür', document.querySelector('.conditions').textContent.includes('Paketli ürünler hariç.') && document.querySelector('.conditions').textContent.includes('100 TL'));

  await navigate(`admin/businesses?edit=${business.id}`);
  input('#edit-partnershipStatus', 'ended'); await submit('#business-form'); await confirm();
  check('İş ortaklığı bittiğinde avantaj askıya alınır', benefit.publicationStatus === 'suspended' && s.statusOf(benefit) === 'suspended');
  await navigate(`admin/businesses?edit=${business.id}`);
  input('#edit-partnershipStatus', 'active'); await submit('#business-form');
  check('Anlaşmayı yeniden açmak avantajı kontrolsüz yayımlamaz', benefit.publicationStatus === 'suspended');
  await navigate(`admin/benefits?edit=${benefit.id}`);
  document.querySelector('[name=reviewed]').checked = true;
  await submit('#benefit-form', '[value=publish]'); await confirm();
  check('İş ortaklığı yenilendikten sonra kontrollü yeniden yayın', s.statusOf(benefit) === 'active');

  await navigate('admin/students');
  click('[data-admin=approve][data-id=user-a]'); await confirm();
  check('Örnek öğrenciyi onaylama', s.users.find(item => item.id === 'user-a').status === 'active');
  click('[data-admin=reject][data-id=user-b]'); await confirm();
  check('Örnek öğrenciyi reddetme', s.users.find(item => item.id === 'user-b').status === 'rejected');
  await navigate('admin/users');
  click('[data-admin=role][data-id=user-a]'); input('#edit-role', 'admin'); await confirm();
  check('Temel rol düzenleme', s.users.find(item => item.id === 'user-a').role === 'admin');
  await navigate('admin/audit');
  check('İşlem günlüğü demo işlemlerini kaydeder', s.state.audit.some(item => item.type === 'Avantaj yayımlandı') && s.state.audit.some(item => item.type === 'Öğrenci hesabı reddedildi'));
  input('#admin-search', 'Avantaj yayımlandı');
  check('İşlem günlüğü araması', document.querySelectorAll('.admin-table tbody tr').length === 3);
  await navigate('admin/settings'); input('#edit-SCHOOL_EMAIL_DOMAIN', 'yeni.ogrenci.example'); input('#edit-PLATFORM_NAME', 'KoçBenefits Test');
  await submit('#settings-form'); await confirm();
  check('Platform adı ve alan adı ayarı uygulanır', s.settings.PLATFORM_NAME === 'KoçBenefits Test' && document.querySelector('.sidebar .brand').textContent.includes('KoçBenefits Test') && s.users.every(item => item.email.endsWith('@yeni.ogrenci.example')));
  input('#edit-SCHOOL_EMAIL_DOMAIN', 'ogrenci.example'); input('#edit-PLATFORM_NAME', 'KoçBenefits');
  await submit('#settings-form'); await confirm();
  check('Örnek ayarlar geri değiştirilebilir', s.settings.SCHOOL_EMAIL_DOMAIN === 'ogrenci.example');
  check('Demo yönetim verileri tarayıcıya yazılır', JSON.parse(localStorage.getItem(KOC_CONFIG.DEMO_STORAGE_KEY)).benefits.some(item => item.id === benefit.id));

  click('[data-action=logout]'); click('[data-auth-mode=register]');
  input('#auth-name', 'Yeni Örnek Öğrenci'); input('#auth-email', 'yeni.ornek@ogrenci.example'); await submit('#auth-form');
  check('Yeni demo kayıt bekleme listesine girer', s.users.some(item => item.email === 'yeni.ornek@ogrenci.example' && item.verification === 'pending') && document.querySelector('#app-view').hidden);
  click('[data-action=sample-login]'); await wait(); await navigate('discover');
  check('Yayınlanan demo öğrenci kataloğuna yansır', document.querySelector(`[data-card="${benefit.id}"]`));
  await navigate(`benefit/${benefit.id}`);
  check('Öğrenci detayında favori kontrolü', document.querySelector('[data-favorite]') && document.querySelector('[data-benefit-state=active]'));
  await navigate('benefit/mola'); click('[data-action=reveal]'); click('[data-action=copy-code]'); await wait();
  check('Güncellenen detayda kod gerçekten kopyalanır', (await navigator.clipboard.readText()) === 'DEMO-MOLA20');
  const beforeViews = s.state.views.mola;
  click('[data-action=logout]'); await navigate(`benefit/${benefit.id}`); click('[data-action=sample-login]'); await wait();
  check('Paylaşılan bağlantı giriş sonrasında korunur', location.hash === `#benefit/${benefit.id}` && document.querySelector('.detail-title').textContent === benefit.title);
  check('Kullanım kayıtları görüntülemelerden türetilmez', !s.state.usage && s.state.views.mola === beforeViews);
  click('[data-action=logout]'); click('[data-auth-audience=admin]'); click('[data-action=sample-admin-login]'); await wait();
  await navigate('admin/analytics');
  check('Analitik yalnızca yerel demo görüntülemelerini gösterir', document.querySelector('.bar-chart').textContent.includes('Mola Coffee') && document.querySelector('main').textContent.includes('Kayıt yok'));
  await navigate('admin/overview');
  return { checks, newBenefitId: benefit.id, auditEntries: s.state.audit.length };
})()
