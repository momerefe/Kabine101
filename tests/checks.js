// tests/run_browser_checks.py tarafından gerçek tarayıcıda çalıştırılır.
(async () => {
  const checks = [];
  const check = (name, condition) => checks.push({ name, passed: Boolean(condition) });
  const wait = () => new Promise(resolve => setTimeout(resolve, 70));
  const navigate = async hash => { location.hash = hash; await wait(); };
  const click = selector => document.querySelector(selector).click();
  const submit = selector => document.querySelector(selector).dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
  const input = (selector, value) => { const element = document.querySelector(selector); element.value = value; element.dispatchEvent(new Event('input', { bubbles: true })); };
  localStorage.removeItem(KOC_CONFIG.FAVORITES_STORAGE_KEY);
  check('Başlangıçta yalnızca demo giriş ekranı', !document.querySelector('#auth-view').hidden && document.querySelector('#app-view').hidden);
  for (const email of ['deniz@gmail.com', 'deniz@ogrenci.example.evil.org', 'deniz@sub.ogrenci.example', 'deniz@@ogrenci.example', '.deniz@ogrenci.example']) {
    input('#auth-email', email); submit('#auth-form'); await wait();
    check(`İzin verilmeyen adres reddedilir: ${email}`, !document.querySelector('#auth-error').hidden && document.querySelector('#app-view').hidden);
  }
  click('[data-auth-mode=register]');
  input('#auth-email', 'deniz@ogrenci.example'); input('#auth-name', ' '); submit('#auth-form'); await wait();
  check('Kayıtta boş ad reddedilir', !document.querySelector('#auth-error').hidden);
  input('#auth-name', 'Deniz Örnek'); input('#auth-email', 'deniz@OGRENCI.EXAMPLE'); submit('#auth-form'); await wait();
  check('Doğru örnek alan adıyla demo kayıt/giriş', !document.querySelector('#app-view').hidden && location.hash === '#overview');
  check('Altı ana navigasyon bölümü', document.querySelectorAll('#desktop-nav a').length === 6);
  check('Altı kategoriye erişim', document.querySelectorAll('.category-tile').length === 6);
  check('Gerçekmiş gibi tasarruf istatistiği sunulmaz', !/₺|toplam tasarruf/i.test(document.querySelector('main').textContent));
  click('[data-favorite=mola]');
  check('Karttan favoriye ekleme', document.querySelector('[data-favorite=mola]').getAttribute('aria-pressed') === 'true');
  check('Favori tarayıcıya kaydedilir', JSON.parse(localStorage.getItem(KOC_CONFIG.FAVORITES_STORAGE_KEY)).includes('mola'));
  await navigate('favorites');
  check('Favori sayfasında doğru kart', document.querySelectorAll('.benefit-card').length === 1 && document.querySelector('[data-card=mola]'));
  click('[data-favorite=mola]');
  check('Favoriden çıkarma ve boş durum', document.querySelectorAll('.benefit-card').length === 0 && document.querySelector('.empty-state'));
  await navigate('discover');
  check('Katalogda altı demo avantaj', document.querySelectorAll('.benefit-card').length === 6);
  click('[data-category=tech]');
  check('Kategori filtresi', document.querySelectorAll('.benefit-card').length === 1 && document.querySelector('[data-card=ses]'));
  input('#catalog-query', 'kahve');
  check('Arama ve kategori birlikte uygulanır', document.querySelectorAll('.benefit-card').length === 0 && document.querySelector('.empty-state'));
  click('[data-action=reset-filters]');
  check('Filtre ve aramayı sıfırlama', document.querySelectorAll('.benefit-card').length === 6 && document.querySelector('#catalog-query').value === '');
  input('#catalog-query', 'MOLA');
  check('Büyük/küçük harften bağımsız arama', document.querySelectorAll('.benefit-card').length === 1 && document.querySelector('[data-card=mola]'));
  await navigate('benefit/mola');
  check('İşletmeye uygun tek kullanım yöntemi', document.querySelectorAll('[data-action=reveal]').length === 1 && !document.querySelector('.qr-box'));
  click('[data-action=reveal]');
  check('Demo kodu gösterilir', document.querySelector('#discount-code').value === 'DEMO-MOLA20');
  click('[data-action=copy-code]'); await wait();
  check('Kopyalama sonucu veya elle kopyalama açıklaması', document.querySelector('[data-action=copy-code]').textContent.includes('kopyalandı') || !document.querySelector('#copy-hint').hidden);
  click('[data-favorite=mola]');
  check('Detaydan favori ekleme', document.querySelector('[data-favorite=mola]').getAttribute('aria-pressed') === 'true');
  await navigate('benefit/rota');
  const link = document.querySelector('.redeem-panel a');
  check('Örnek bağlantı güvenli yeni sekmede açılır', link?.href.startsWith('https://example.org/') && link.target === '_blank' && link.rel.includes('noopener'));
  await navigate('benefit/kort'); click('[data-action=reveal]');
  const qrImage = document.querySelector('.qr-box img');
  await qrImage.decode();
  check('Yerel demo QR görseli yüklenir', qrImage.naturalWidth > 0 && qrImage.alt.includes('DEMO-KOCBENEFITS'));
  let qrDecoded = 'Tarayıcı QR çözücüsü desteklemiyor';
  if ('BarcodeDetector' in window && (await BarcodeDetector.getSupportedFormats()).includes('qr_code')) {
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = 290;
    canvas.getContext('2d').drawImage(qrImage, 0, 0, 290, 290);
    const codes = await new BarcodeDetector({ formats: ['qr_code'] }).detect(canvas);
    qrDecoded = codes[0]?.rawValue || 'QR okunamadı';
    check('QR gerçekten örnek metni kodlar', qrDecoded === 'DEMO-KOCBENEFITS');
  }
  await navigate('history');
  check('Kod ve QR açılması kullanım kaydı üretmez', document.querySelector('.history-notice') && document.querySelector('.empty-state') && !document.querySelector('table'));
  await navigate('benefit/sayfa');
  check('Süresi dolmuş avantaj kullanıma kapalı', document.querySelector('.expired-panel button').disabled && !document.querySelector('[data-action=reveal]'));
  await navigate('benefit/ses');
  check('Belirtilmemiş tarih açıkça gösterilir', document.querySelector('.date-info').textContent.includes('tarih belirtilmedi'));
  await navigate('profile'); input('#profile-name', '<img src=x onerror=alert(1)>'); submit('#profile-form');
  check('Örnek profil girdisi HTML olarak çalıştırılmaz', document.querySelector('.profile-summary h2').textContent.includes('<img') && !document.querySelector('.profile-summary h2 img'));
  input('#profile-name', 'Deniz Örnek'); submit('#profile-form');
  check('Profil ve üst menü birlikte güncellenir', document.querySelector('.profile-summary h2').textContent === 'Deniz Örnek' && document.querySelector('#header-name').textContent === 'Deniz');
  await navigate('help');
  check('Yardım ve destek açıklamaları', document.querySelectorAll('details').length >= 6 && document.querySelector('.support-card').textContent.includes('henüz bir destek kanalı tanımlanmadı'));
  await navigate('benefit/bulunamayan');
  check('Geçersiz detay bağlantısında hata durumu', document.querySelector('.empty-state h2').textContent.includes('bulamadık'));
  document.querySelector('[data-action=logout]').click();
  check('Çıkışta girişe dönülür', !document.querySelector('#auth-view').hidden && document.querySelector('#app-view').hidden);
  await navigate('profile');
  check('Demo çıkışından sonra doğrudan panel bağlantısı açılmaz', document.querySelector('#app-view').hidden);
  click('[data-action=sample-login]'); await wait();
  check('Tek tıkla örnek öğrenci akışı', location.hash === '#overview' && document.querySelector('#header-name').textContent === 'Deniz');
  const images = [...document.querySelectorAll('main img')];
  await Promise.all(images.map(image => image.decode()));
  check('Ana ekrandaki tüm yerel görseller yüklenir', images.every(image => image.naturalWidth > 0 && !image.dataset.failed));
  check('Masaüstünde yatay taşma yok', document.documentElement.scrollWidth <= innerWidth);
  return { checks, qrDecoded };
})()
